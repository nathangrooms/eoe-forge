#!/usr/bin/env node
/**
 * Generate the counter-name table from XMage's `CounterType` enum.
 *
 * Derived from XMage, which is MIT licensed, Copyright (c) 2010
 * betasteward@gmail.com, https://github.com/magefree/mage. Read in place, never
 * vendored. Forge is GPL-3.0 and was not fetched, read or referenced.
 *
 * `AddCountersSourceEffect` blocks 1,103 cards and `AddCountersTargetEffect`
 * another 769, and both name their counter as a `CounterType` enum member. The
 * member is `P1P1`; the counter is `+1/+1`. Eleven members spell themselves
 * through `new BoostCounter(p, t).name` rather than as a literal, and the sign
 * rule for those is XMage's `CardUtil.getBoostCountAsStr`: a zero next to a
 * negative prints as `-0`, so `M1M0` is `-1/-0` and not `-1/+0`. That rule is
 * reproduced here rather than approximated, because `-1/-0` and `-1/+0` are
 * different strings and a lookup on the wrong one finds nothing.
 *
 * Run:
 *   node scripts/xmage/extract-counters.mjs
 * Writes:
 *   src/lib/cards/xmage/counters.generated.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
const XMAGE_ROOT =
  process.env.XMAGE_ROOT || 'C:/Users/natha/AppData/Local/Temp/claude/xmage-spike/mage';
const FILE = path.join(XMAGE_ROOT, 'Mage/src/main/java/mage/counters/CounterType.java');

const src = readFileSync(FILE, 'utf8');
const table = {};

/** XMage `CardUtil.getBoostCountAsStr`, reproduced exactly. */
function boostName(power, toughness) {
  let p = String(power);
  let t = String(toughness);
  if (!p.startsWith('-')) p = t.startsWith('-') && p === '0' ? '-0' : `+${p}`;
  if (!t.startsWith('-')) t = p.startsWith('-') && t === '0' ? '-0' : `+${t}`;
  return `${p}/${t}`;
}

let literal = 0;
let boost = 0;
for (const line of src.split('\n')) {
  const lit = /^ {4}([A-Z0-9_]+)\("([^"]*)"\)/.exec(line);
  if (lit) {
    table[lit[1]] = lit[2];
    literal += 1;
    continue;
  }
  const b = /^ {4}([A-Z0-9_]+)\(new BoostCounter\((-?\d+), *(-?\d+)\)\.name\)/.exec(line);
  if (b) {
    table[b[1]] = boostName(Number(b[2]), Number(b[3]));
    boost += 1;
  }
}

const generated = `/**
 * GENERATED by scripts/xmage/extract-counters.mjs. Do not edit by hand.
 *
 * XMage \`CounterType\` enum members as the counter names \`dsl.ts\` uses.
 *
 * Derived from XMage, which is MIT licensed, Copyright (c) 2010
 * betasteward@gmail.com, https://github.com/magefree/mage. Read in place and
 * not vendored; these are counter names, which are game vocabulary rather than
 * rules text. Forge is GPL-3.0 and was not fetched, read or referenced.
 *
 * ${literal} spelled as literals, ${boost} spelled through BoostCounter, ${literal + boost} total.
 */

export const XMAGE_COUNTERS: Record<string, string> = ${JSON.stringify(table, null, 1)};
`;

writeFileSync(path.join(REPO, 'src/lib/cards/xmage/counters.generated.ts'), generated);
console.log(`counter types read  ${literal + boost}  (${literal} literal, ${boost} boost)`);
console.log(`  P1P1 -> ${table.P1P1}   M1M1 -> ${table.M1M1}   M1M0 -> ${table.M1M0}   CHARGE -> ${table.CHARGE}`);
